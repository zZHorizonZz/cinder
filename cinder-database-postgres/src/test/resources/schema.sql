CREATE TABLE customers (
  id VARCHAR(20) PRIMARY KEY,
  email VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(50) NOT NULL
);

DROP TYPE IF EXISTS order_state;

CREATE TYPE order_state AS ENUM ('OPEN', 'PAID', 'SHIPPED', 'CLOSED', 'CANCELLED', 'ARCHIVED', 'LOST');

CREATE TABLE orders (
  id BIGINT PRIMARY KEY,
  customer_id VARCHAR(20) NOT NULL,
  state order_state NOT NULL,
  total_cents BIGINT NOT NULL,
  version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  cancel_time TIMESTAMPTZ
);

CREATE TABLE items (
  id BIGINT PRIMARY KEY,
  order_id BIGINT NOT NULL,
  product VARCHAR(50) NOT NULL,
  quantity INT NOT NULL,
  position INT NOT NULL
);

CREATE TABLE files (
  id BIGINT PRIMARY KEY,
  content BYTEA
);

CREATE TABLE categories (
  id BIGINT PRIMARY KEY,
  parent_id BIGINT,
  name VARCHAR(50) NOT NULL
);

CREATE TABLE tags (
  id BIGINT PRIMARY KEY,
  label VARCHAR(50) NOT NULL
);

CREATE TABLE customer_tags (
  customer_id VARCHAR(20) NOT NULL,
  tag_id BIGINT NOT NULL,
  PRIMARY KEY (customer_id, tag_id)
);

CREATE TABLE notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body VARCHAR(100) NOT NULL,
  slug VARCHAR(100)
);

CREATE OR REPLACE FUNCTION notes_slug() RETURNS trigger AS $$ BEGIN NEW.slug := lower(NEW.body); RETURN NEW; END $$ LANGUAGE plpgsql;

CREATE TRIGGER notes_slug BEFORE INSERT OR UPDATE ON notes FOR EACH ROW EXECUTE FUNCTION notes_slug();
